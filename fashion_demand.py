##Data: downloading from Google Trends, then reusing the saved file

def fetch_trends(terms):
    try:
        from pytrends.request import TrendReq
    except ImportError:
        sys.exit("pytrends is not installed. Run: pip install pytrends")
    pt = TrendReq(hl="en-GB", tz=0)
    series = {}
    for term in terms:
        for attempt in range(5):
            try:
                pt.build_payload([term], timeframe=timeframe, geo=geo)
                d = pt.interest_over_time()
                if d.empty:
                    raise RuntimeError("empty response")
                if "isPartial" in d.columns:
                    d = d[~d["isPartial"].astype(bool)]   ##drop the unfinished latest week
                series[term] = d[term]
                print(f"downloaded: {term}")
                break
            except Exception as e:
                wait = 30 * (attempt + 1) + random.uniform(0, 10)
                print(f"{term}: {type(e).__name__}: {e}. Retrying in {wait:.0f}s")
                time.sleep(wait)
        else:
            print(f"skipped: {term}")
        time.sleep(random.uniform(6, 12))
    if len(series) < 8:
        sys.exit("Fewer than 8 terms downloaded. Wait a while and rerun (finished terms are not lost only if "
                 "the run completes), or try a different network.")
    df = pd.DataFrame(series)
    df.index.name = "week"
    os.makedirs(os.path.dirname(cache), exist_ok=True)
    df.to_csv(cache)
    print(f"Saved {cache}. Retrieved on {pd.Timestamp.now().date()} (record this in your README).")
    return df


def load_data(csv_path):
    path = csv_path or (cache if os.path.exists(cache) else None)
    if path is None:
        return fetch_trends(terms)
    df = pd.read_csv(path, parse_dates=["week"]).set_index("week").sort_index()
    print(f"Loaded {path}")
    return df

##Features

Features = ["term", "lag1", "lag2", "lag3", "lag4", "mean4", "mean12", "woy_sin", "woy_cos"]


def build_panel(wide):
    weeks = pd.date_range(wide.index.min(), wide.index.max(), freq="7D")
    wide = wide.reindex(weeks).interpolate(limit=2)    ##fill rare one-week gaps only
    wide = wide.dropna(axis=1, thresh=int(len(weeks) * 0.95))
    long = wide.stack().rename("value").reset_index()
    long.columns = ["week", "term", "value"]
    long = long.sort_values(["term", "week"]).reset_index(drop=True)
    long["y"] = np.log1p(long["value"])
    g = long.groupby("term")["y"]
    for k in range(1, 5):
        long[f"lag{k}"] = g.shift(k)
    long["mean4"] = long[[f"lag{k}" for k in range(1, 5)]].mean(axis=1)
    long["mean12"] = sum(g.shift(k) for k in range(1, 13)) / 12
    gv = long.groupby("term")["value"]
    long["v_lag1"] = gv.shift(1)
    long["v_mean4"] = sum(gv.shift(k) for k in range(1, 5)) / 4
    long["v_lag52"] = gv.shift(52)
    woy = long["week"].dt.isocalendar().week.astype(int)
    long["woy_sin"] = np.sin(2 * np.pi * woy / 52.0)
    long["woy_cos"] = np.cos(2 * np.pi * woy / 52.0)
    long["term"] = long["term"].astype("category")
    return long, wide

def fit_gb(train):
    m = HistGradientBoostingRegressor(
        max_iter=200, learning_rate=0.05, max_leaf_nodes=8, min_samples_leaf=10,
        l2_regularization=1.0, categorical_features="from_dtype", random_state=seed)
    return m.fit(train[Features], train["y"])


def predict_value(model, rows):
    return np.clip(np.expm1(model.predict(rows[Features])), 0, None)

##Evaluation

def evaluate(long):
    usable = long.dropna(subset=["mean12"])
    all_weeks = np.sort(long["week"].unique())
    cutoff = pd.Timestamp(all_weeks[int(len(all_weeks) * train_share)])
    frozen = fit_gb(usable[usable.week < cutoff])
    test_weeks = [w for w in all_weeks if pd.Timestamp(w) >= cutoff]
    rows = []
    for w in test_weeks:
        cur = usable[(usable.week == w) & usable.v_lag52.notna()]
        if cur.empty:
            continue
        retrained = fit_gb(usable[usable.week < w])   ##earlier weeks only
        preds = {
            "last week": cur["v_lag1"].to_numpy(),
            "average of last 4 weeks": cur["v_mean4"].to_numpy(),
            "same week last year": cur["v_lag52"].to_numpy(),
            "gradient boosting, frozen": predict_value(frozen, cur),
            "gradient boosting, retrained weekly": predict_value(retrained, cur),
        }
        for name, p in preds.items():
            rows.append({"week": pd.Timestamp(w), "model": name,
                         "abs_err": float(np.abs(cur["value"].to_numpy() - p).sum()),
                         "actual": float(cur["value"].sum())})
    res = pd.DataFrame(rows)
    res["month"] = res["week"].dt.to_period("M").dt.to_timestamp()
    monthly = res.groupby(["month", "model"])[["abs_err", "actual"]].sum().reset_index()
    monthly["wape_pct"] = monthly.abs_err / monthly.actual * 100
    res["months_since_cutoff"] = ((res["week"] - cutoff).dt.days / 30.44)
    return res, monthly, cutoff

##Plots

style = {   # model: (colour, linestyle, linewidth)
    "same week last year": ("#64748B", "--", 1.8),
    "last week": ("#C2410C", "-", 1.8),
    "average of last 4 weeks": ("#0F766E", "-", 1.8),
    "gradient boosting, frozen": ("#7C3AED", "-", 1.8),
    "gradient boosting, retrained weekly": ("#1B3BD6", "-", 2.6),
}
line_colours = ["#1B3BD6", "#C2410C", "#0F766E", "#7C3AED", "#B45309", "#475569"]

def plot_seasonality(wide):
    seasonal = (wide.std() / wide.mean().clip(lower=1)).nlargest(6).index
    fig, ax = plt.subplots(figsize=(9, 4.6))
    for c, col in zip(seasonal, line_colours):
        ax.plot(wide.index, wide[c], lw=1.5, color=col, label=c)
    ax.set_ylabel("UK search interest (0 to 100)")
    ax.set_title("Fashion searches peak in different seasons")
    ax.legend(fontsize=8, ncol=3, frameon=False, loc="upper left")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(f"{out}/seasonality.png", dpi=160); plt.close(fig)


def plot_error(monthly, cutoff):
    fig, ax = plt.subplots(figsize=(9, 4.6))
    for name, (col, ls, lw) in style.items():
        m = monthly[monthly.model == name]
        ax.plot(m.month, m.wape_pct, marker="o", ms=3, lw=lw, ls=ls, label=name, color=col)
    ax.axvline(cutoff, color="k", ls=":", lw=1)
    ax.text(cutoff, ax.get_ylim()[1], " frozen model's training ends", va="top", fontsize=8)
    ax.set_ylabel("Forecast error (WAPE, % of search index)")
    ax.set_title("Forecast error by month after the frozen model stops learning")
    ax.legend(fontsize=8, frameon=False)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout(); fig.savefig(f"{out}/forecast_error_by_month.png", dpi=160); plt.close(fig)

