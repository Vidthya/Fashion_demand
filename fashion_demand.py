def main(csv_path):
    os.makedirs(out, exist_ok=True)
    wide_raw = load_data(csv_path)
    long, wide = build_panel(wide_raw)
    print(f"{wide.shape[0]} weeks ({wide.index.min().date()} to {wide.index.max().date()}), {wide.shape[1]} terms")
    wide.to_csv(f"{out}/weekly_search_interest_used.csv")
    plot_seasonality(wide)
    res, monthly, cutoff = evaluate(long)
    monthly.to_csv(f"{out}/monthly_wape.csv", index=False)
    plot_error(monthly, cutoff)

    first = res[res.months_since_cutoff < 12]
    later = res[res.months_since_cutoff >= 12]
    def agg(d):
        g = d.groupby("model")[["abs_err", "actual"]].sum()
        return (g.abs_err / g.actual * 100).round(1)
    summary = pd.DataFrame({"first 12 months after cutoff (WAPE %)": agg(first),
                            "after 12 months (WAPE %)": agg(later) if len(later) else np.nan})
    summary.to_csv(f"{out}/summary_wape.csv")
    print(f"\nFrozen model trained on weeks before {cutoff.date()}; the retrained model refits every week on earlier weeks only.")
    print("\n=== Forecast error (WAPE %, lower is better) ===")
    print(summary.to_string())
    print("\n=== Monthly WAPE % ===")
    print(monthly.pivot(index="month", columns="model", values="wape_pct").round(1).to_string())
    print("\nSaved tables and plots to results/")


